#!/usr/bin/env python3
"""Install (or uninstall) the ``RamFix`` command so it works from any directory.

Usage:
    python install.py                 # install system-wide if possible, else user
    python install.py --user          # force a per-user install
    python install.py --prefix /opt/ramfix
    python install.py --uninstall
"""

from __future__ import annotations

import argparse
import os
import platform
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

APP_DIR = Path(__file__).resolve().parent
PACKAGE_NAME = "ramfix"
COMMAND = "RamFix"
# Aliases so the command works with any capitalisation (e.g. `ramfix`,
# `RAMFIX`) on case-sensitive filesystems. On case-insensitive filesystems a
# single launcher already answers to every spelling.
COMMANDS = ("RamFix", "ramfix", "RAMFIX")
PATH_MARKER_START = "# >>> ramfix >>>"
PATH_MARKER_END = "# <<< ramfix <<<"


# --------------------------------------------------------------------------- #
# Output helpers
# --------------------------------------------------------------------------- #


def info(message: str) -> None:
    print(message)


def good(message: str) -> None:
    print(f"[ OK ] {message}")


def bad(message: str) -> None:
    print(f"[FAIL] {message}")


# --------------------------------------------------------------------------- #
# Paths
# --------------------------------------------------------------------------- #


def is_windows() -> bool:
    return os.name == "nt" or platform.system().lower().startswith("windows")


def is_admin() -> bool:
    if is_windows():
        try:
            import ctypes

            return bool(ctypes.windll.shell32.IsUserAnAdmin())
        except Exception:
            return False
    return hasattr(os, "geteuid") and os.geteuid() == 0


def default_dirs(*, user: bool) -> tuple[Path, Path]:
    """Return ``(bin_dir, lib_dir)`` for the requested install scope."""
    if is_windows():
        base = Path(os.environ.get("LOCALAPPDATA", Path.home() / "AppData" / "Local")) / "RamFix"
        return base / "bin", base / "lib"
    if user or not is_admin():
        base = Path.home() / ".local"
        return base / "bin", base / "lib" / "ramfix-app"
    return Path("/usr/local/bin"), Path("/usr/local/lib/ramfix-app")


def resolve_dirs(args: argparse.Namespace) -> tuple[Path, Path]:
    if args.prefix:
        prefix = Path(args.prefix).expanduser().resolve()
        return prefix / "bin", prefix / "lib" / "ramfix-app"
    return default_dirs(user=args.user)


def filesystem_is_case_insensitive(directory: Path) -> bool:
    """Probe whether *directory* lives on a case-insensitive filesystem."""
    probe = directory / ".ramfix-case-probe"
    twin = directory / ".RAMFIX-CASE-PROBE"
    try:
        probe.write_text("x", encoding="utf-8")
        return twin.exists()
    except OSError:
        return is_windows()
    finally:
        try:
            probe.unlink()
        except OSError:
            pass


def launcher_paths(bin_dir: Path) -> list[Path]:
    """Every command spelling that should be available in *bin_dir*."""
    suffix = ".cmd" if is_windows() else ""
    if is_windows() or filesystem_is_case_insensitive(bin_dir):
        return [bin_dir / f"{COMMAND}{suffix}"]
    return [bin_dir / f"{name}{suffix}" for name in COMMANDS]


# --------------------------------------------------------------------------- #
# Install
# --------------------------------------------------------------------------- #


def copy_package(lib_dir: Path) -> bool:
    """Copy the ramfix package into the install location."""
    source = APP_DIR / PACKAGE_NAME
    if not source.is_dir():
        bad(f"Cannot find package directory: {source}")
        return False
    destination = lib_dir / PACKAGE_NAME
    try:
        lib_dir.mkdir(parents=True, exist_ok=True)
        if destination.exists():
            shutil.rmtree(destination)
        shutil.copytree(
            source,
            destination,
            ignore=shutil.ignore_patterns("__pycache__", "*.py[co]"),
        )
    except OSError as exc:
        bad(f"Could not copy package to {destination}: {exc}")
        return False
    good(f"Installed package to {destination}")
    return True


def write_launcher(bin_dir: Path, lib_dir: Path) -> bool:
    """Create the executable(s) that put the app on PATH."""
    paths = launcher_paths(bin_dir)
    primary = paths[0]
    try:
        bin_dir.mkdir(parents=True, exist_ok=True)
        if is_windows():
            python = sys.executable
            content = (
                "@echo off\r\n"
                f"rem Generated by {COMMAND} install.py\r\n"
                f'set "PYTHONPATH={lib_dir};%PYTHONPATH%"\r\n'
                f'"{python}" -m {PACKAGE_NAME} %*\r\n'
            )
        else:
            python = sys.executable
            content = (
                "#!/bin/sh\n"
                f"# Generated by {COMMAND} install.py\n"
                f"PYTHONPATH={shlex.quote(str(lib_dir))}${{PYTHONPATH:+:$PYTHONPATH}}; export PYTHONPATH\n"
                f'exec {shlex.quote(python)} -m {PACKAGE_NAME} "$@"\n'
            )

        primary.write_text(content, encoding="utf-8")
        if not is_windows():
            primary.chmod(0o755)

        # Point every other spelling at the primary launcher. A copy is used as
        # a fallback for filesystems that do not support symlinks.
        for alias in paths[1:]:
            if alias.exists() or alias.is_symlink():
                alias.unlink()
            try:
                alias.symlink_to(primary.name)
            except OSError:
                alias.write_text(content, encoding="utf-8")
                alias.chmod(0o755)
    except OSError as exc:
        bad(f"Could not write launcher {primary}: {exc}")
        return False

    names = ", ".join(path.name for path in paths)
    good(f"Created commands: {names}")
    return True


def ensure_dependencies() -> bool:
    """Make sure psutil is importable by the interpreter we use."""
    try:
        subprocess.run(
            [sys.executable, "-c", "import psutil"],
            check=True,
            capture_output=True,
        )
        good("psutil is already available")
        return True
    except subprocess.CalledProcessError:
        pass
    info("Installing psutil...")
    command = [sys.executable, "-m", "pip", "install", "psutil"]
    if not is_admin() and not is_windows():
        command.append("--user")
    try:
        result = subprocess.run(command, check=False)
        if result.returncode == 0:
            good("Installed psutil")
            return True
    except OSError as exc:
        bad(f"Could not run pip: {exc}")
    bad("Could not install psutil automatically. Run: pip install psutil")
    return False


def add_to_path(bin_dir: Path) -> None:
    """Make bin_dir available on PATH for future shells."""
    bin_str = str(bin_dir)
    if bin_str in os.environ.get("PATH", "").split(os.pathsep):
        good("Install directory is already on PATH")
        return
    if is_windows():
        _windows_add_path(bin_str)
        return
    _unix_add_path(bin_str)


def _unix_add_path(bin_str: str) -> None:
    shell = os.environ.get("SHELL", "")
    candidates = []
    if ".zsh" in shell:
        candidates.append(Path.home() / ".zshrc")
    candidates += [Path.home() / ".bashrc", Path.home() / ".bash_profile", Path.home() / ".profile"]
    rc = next((path for path in candidates if path.exists()), candidates[-1])
    block = (
        f"\n{PATH_MARKER_START}\n"
        f"export PATH={shlex.quote(bin_str)}:$PATH\n"
        f"{PATH_MARKER_END}\n"
    )
    try:
        content = rc.read_text(encoding="utf-8") if rc.exists() else ""
        if PATH_MARKER_START in content:
            good(f"PATH entry already present in {rc}")
            return
        rc.write_text(content + block, encoding="utf-8")
        good(f"Added {bin_str} to PATH in {rc} (new terminals will pick it up)")
    except OSError as exc:
        bad(f"Could not update {rc}: {exc}")
        info(f"Add this line to your shell config manually:\n  export PATH={bin_str}:$PATH")


def _windows_add_path(bin_str: str) -> None:
    try:
        import winreg

        with winreg.OpenKey(
            winreg.HKEY_CURRENT_USER, "Environment", 0, winreg.KEY_READ | winreg.KEY_WRITE
        ) as key:
            existing, _ = winreg.QueryValueEx(key, "Path")
            parts = [part for part in existing.split(";") if part]
            if bin_str in parts:
                good("Install directory is already on PATH")
                return
            parts.append(bin_str)
            winreg.SetValueEx(key, "Path", 0, winreg.REG_EXPAND_SZ, ";".join(parts))

        # Ask running applications to refresh their environment.
        import ctypes

        ctypes.windll.user32.SendMessageW(0xFFFF, 0x001A, 0, "Environment")
        good(f"Added {bin_str} to the user PATH")
    except Exception as exc:
        bad(f"Could not update PATH automatically: {exc}")
        info(f"Add this directory to your PATH manually:\n  {bin_str}")


def verify(paths: list[Path]) -> bool:
    """Run every installed command spelling to confirm they work."""
    all_ok = True
    for launcher in paths:
        try:
            if is_windows():
                result = subprocess.run(
                    ["cmd", "/c", str(launcher), "--version"],
                    check=False,
                    capture_output=True,
                    text=True,
                )
            else:
                result = subprocess.run(
                    [str(launcher), "--version"],
                    check=False,
                    capture_output=True,
                    text=True,
                )
        except OSError as exc:
            bad(f"Could not run installed command {launcher.name}: {exc}")
            all_ok = False
            continue
        if result.returncode == 0:
            good(f"Verified {launcher.name}: {result.stdout.strip()}")
        else:
            bad(f"{launcher.name} failed: {result.stderr.strip() or result.stdout.strip()}")
            all_ok = False
    return all_ok


def install(args: argparse.Namespace) -> int:
    bin_dir, lib_dir = resolve_dirs(args)
    info(f"Installing {COMMAND} into {bin_dir} (package in {lib_dir})")

    if not copy_package(lib_dir):
        return 1
    if not write_launcher(bin_dir, lib_dir):
        return 1
    if not args.no_deps and not ensure_dependencies():
        info("Continuing, but the command may need psutil installed manually.")
    if not args.no_path:
        add_to_path(bin_dir)
    if not verify(launcher_paths(bin_dir)):
        return 1

    print()
    good(f"Done. Try: {COMMAND} status (or ramfix / RAMFIX)")
    if not is_windows() and bin_dir not in [Path(p) for p in os.environ.get("PATH", "").split(os.pathsep)]:
        info("Open a new terminal (or source your shell config) before using the command.")
    return 0


# --------------------------------------------------------------------------- #
# Uninstall
# --------------------------------------------------------------------------- #


def remove_from_path(bin_dir: Path) -> None:
    bin_str = str(bin_dir)
    if is_windows():
        try:
            import winreg

            with winreg.OpenKey(
                winreg.HKEY_CURRENT_USER, "Environment", 0, winreg.KEY_READ | winreg.KEY_WRITE
            ) as key:
                existing, _ = winreg.QueryValueEx(key, "Path")
                parts = [p for p in existing.split(";") if p and p != bin_str]
                winreg.SetValueEx(key, "Path", 0, winreg.REG_EXPAND_SZ, ";".join(parts))
            good("Removed PATH entry")
        except Exception as exc:
            bad(f"Could not update PATH: {exc}")
        return

    candidates = [
        Path.home() / ".zshrc",
        Path.home() / ".bashrc",
        Path.home() / ".bash_profile",
        Path.home() / ".profile",
    ]
    for rc in candidates:
        if not rc.exists():
            continue
        try:
            content = rc.read_text(encoding="utf-8")
            if PATH_MARKER_START not in content:
                continue
            lines = content.splitlines(keepends=True)
            cleaned = []
            skipping = False
            for line in lines:
                if line.strip() == PATH_MARKER_START:
                    skipping = True
                    continue
                if line.strip() == PATH_MARKER_END:
                    skipping = False
                    continue
                if not skipping:
                    cleaned.append(line)
            rc.write_text("".join(cleaned), encoding="utf-8")
            good(f"Removed PATH entry from {rc}")
        except OSError as exc:
            bad(f"Could not update {rc}: {exc}")


def uninstall(args: argparse.Namespace) -> int:
    bin_dir, lib_dir = resolve_dirs(args)
    removed = False
    try:
        for launcher in launcher_paths(bin_dir):
            if launcher.exists() or launcher.is_symlink():
                launcher.unlink()
                good(f"Removed {launcher}")
                removed = True
        destination = lib_dir / PACKAGE_NAME
        if destination.exists():
            shutil.rmtree(destination)
            good(f"Removed {destination}")
            removed = True
    except OSError as exc:
        bad(f"Could not remove files: {exc}")
        return 1
    if not args.no_path:
        remove_from_path(bin_dir)
    if not removed:
        info("Nothing appeared to be installed at that location.")
    return 0


# --------------------------------------------------------------------------- #
# Entry point
# --------------------------------------------------------------------------- #


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--user", action="store_true", help="install for the current user only")
    parser.add_argument("--prefix", help="custom installation prefix (bin/ and lib/ under it)")
    parser.add_argument("--no-path", action="store_true", help="do not modify PATH")
    parser.add_argument("--no-deps", action="store_true", help="do not install psutil")
    parser.add_argument("--uninstall", action="store_true", help="remove the installed command")
    return parser


def main() -> int:
    args = build_parser().parse_args()
    return uninstall(args) if args.uninstall else install(args)


if __name__ == "__main__":
    raise SystemExit(main())
